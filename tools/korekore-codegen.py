#!/usr/bin/env python3
"""Generate the korekore theme and pixel art as code for the Mac app, the Linux app and the firmware.

The design lives in docs/design/korekore/ (tokens.json and pixel/*.json, see its README), except the agents' icons,
which are the robot screens' (firmware-rs/core/src/agent_icon/pixels.rs); this turns them into:
  - app/Sources/KorekoreUI/KorekoreTheme.swift               colours, type styles and metrics for SwiftUI
  - app/Sources/VibeBuddyCore/Korekore/KorekoreSprites.swift  the sprites as palette-indexed pixels
  - desktop/src/korekore/theme.rs                             the same theme for iced
  - desktop/src/korekore/sprites.rs                           the same sprites
  - firmware-rs/core/src/korekore/theme.rs                    the colours as RGB565
  - firmware-rs/core/src/korekore/sprites.rs                  Kore, the tiles and the tag as static tables in flash

Every sprite is stored the same way: width, height, a palette and one index per pixel, row-major, where 0 is
transparent and n is palette[n - 1]. The pixels are copied as drawn; scaling is left to the renderers, which only
ever scale by whole numbers with nearest-neighbour sampling.

Usage: tools/korekore-codegen.py [--check]
With --check nothing is written; it exits 1 if any generated file is out of date.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DESIGN = ROOT / "docs/design/korekore"
HEADER = "Generated by tools/korekore-codegen.py from docs/design/korekore. Do not edit."

# The fonts both apps bundle (tools/korekore-fonts.py), by weight, as the files name themselves. Google Fonts lists
# the rounded face as "M PLUS Rounded 1c", but inside the files it is "Rounded Mplus 1c", which is what the
# system's font lookup sees.
ROUNDED = {400: "RoundedMplus1c-Regular", 700: "RoundedMplus1c-Bold", 800: "RoundedMplus1c-ExtraBold"}
PIXEL = {400: "DotGothic16-Regular"}
FAMILY_NAMES = {"rounded": "Rounded Mplus 1c", "pixel": "DotGothic16"}
RUST_WEIGHTS = {400: "Normal", 700: "Bold", 800: "ExtraBold"}


def load(name):
    return json.loads((DESIGN / name).read_text())


def hex_rgb(value):
    assert re.fullmatch(r"#[0-9a-fA-F]{6}", value), value
    return int(value[1:], 16)


def rgb565(rgb):
    r, g, b = rgb >> 16, (rgb >> 8) & 0xFF, rgb & 0xFF
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def px(value):
    assert value.endswith("px"), value
    return float(value[:-2])


def number(value):
    return f"{value:g}"


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(part.capitalize() for part in rest)


def upper(name):
    return name.replace("-", "_").upper()


# ---------- tokens ----------


def colors(tokens):
    """(name, rgb, usage) for every colour, with references such as {ink} resolved."""
    values = {t["name"]: t["value"] for t in tokens["color"]["tokens"]}

    def resolve(value):
        reference = re.fullmatch(r"\{(.+)\}", value)
        return resolve(values[reference.group(1)]) if reference else hex_rgb(value)

    return [(t["name"], resolve(t["value"]), t.get("usage", "")) for t in tokens["color"]["tokens"]]


def text_styles(tokens):
    """(name, family, font file, size, line height, weight, letter spacing in px, usage)."""
    styles = []
    for group in tokens["type"]["groups"]:
        family = group["family"]
        files = ROUNDED if family == "rounded" else PIXEL
        for style in group["styles"]:
            size = px(style["fontSize"])
            line = style["lineHeight"]
            line_height = px(line) if isinstance(line, str) else size * line
            spacing = style.get("letterSpacing")
            letter_spacing = float(spacing[:-2]) * size if spacing else 0.0
            weight = style["fontWeight"]
            styles.append((style["name"], family, files[weight], size, round(line_height, 2), weight,
                           round(letter_spacing, 2), style.get("usage", "")))
    return styles


def metrics(tokens, group):
    return [(t["name"], t["value"], t.get("usage", "")) for t in tokens[group]["tokens"]]


def shadow_offset(value):
    # "0 4px 0 #1c1730": x offset, y offset, blur, colour; korekore shadows only drop straight down.
    x, y, blur, _ = value.split()
    assert x == "0" and blur == "0", value
    return px(y)


# ---------- sprites ----------


def sprite(name, rows, palette):
    """Index the rows against the palette: '.' is transparent, other keys map in order of first use."""
    keys, colours, pixels = {}, [], []
    for row in rows:
        assert len(row) == len(rows[0]), (name, row)
        for key in row:
            if key == ".":
                pixels.append(0)
                continue
            if key not in keys:
                colour = hex_rgb(palette[key])
                if colour not in colours:
                    colours.append(colour)
                keys[key] = colours.index(colour) + 1
            pixels.append(keys[key])
    return {"name": name, "width": len(rows[0]), "height": len(rows), "palette": colours, "pixels": pixels}


# The agents' marks as the robot screens' task cards draw them (firmware-rs/core/src/agent_icon/pixels.rs, from
# tools/make-agent-icons.py): the design's 12 × 12 tiles didn't say whose agent it was at a glance, these do.
VENDOR_ICONS = {"CLAUDE": "icon-cc", "CODEX": "icon-cx", "OPENCODE": "icon-oc", "COPILOT": "icon-gh", "PI": "icon-pi", "CI": "icon-ci"}


def vendor_icons():
    text = (ROOT / "firmware-rs/core/src/agent_icon/pixels.rs").read_text()
    out = {}
    for constant, body in re.findall(r"pub const (\w+): \[u16; 256\] = \[(.*?)\];", text, re.S):
        if constant not in VENDOR_ICONS:
            continue
        colours, pixels = [], []
        for value in (int(word, 16) for word in re.findall(r"0x[0-9A-Fa-f]{4}", body)):
            if value == 0:
                pixels.append(0)
                continue
            rgb = ((value >> 11) * 255 // 31) << 16 | (((value >> 5) & 0x3F) * 255 // 63) << 8 | (value & 0x1F) * 255 // 31
            if rgb not in colours:
                colours.append(rgb)
            pixels.append(colours.index(rgb) + 1)
        name = VENDOR_ICONS[constant]
        out[name] = {"name": name, "width": 16, "height": 16, "palette": colours, "pixels": pixels}
    assert len(out) == len(VENDOR_ICONS), "pixels.rs is missing an agent"
    return out


def sprites(tokens):
    """All sprites, each tagged with whether the firmware carries it."""
    color = {name: rgb for name, rgb, _ in colors(tokens)}
    out = []
    kore = load("pixel/kore.json")
    for expression, rows in kore["expressions"].items():
        out.append((sprite(f"kore-{expression}", rows, kore["palette"]), True))
    icons = load("pixel/icons.json")
    vendor = vendor_icons()
    for key, icon in icons["icons"].items():
        name = f"icon-{key.replace('_', '-')}"
        if name in vendor:
            out.append((vendor[name], True))
            continue
        palette = {"o": icons["ink"], "x": icons["ink"], "w": "#FFFFFF", "g": icon["tile"]}
        out.append((sprite(name, icon["tile12"], palette), True))
    tag = load("pixel/pixel-tag-font.json")
    # One colour, which the renderers may tint: kore-pink-text small, kore-pink-tag large (tokens.json).
    pink = "#%06X" % color["kore-pink-text"]
    out.append((sprite("tag-your-vibebuddy", tag["rendered"]["your vibebuddy"], {"x": pink}), True))
    characters = load("pixel/characters.json")
    for who, character in characters["characters"].items():
        # Style drafts for the apps only: the box shows production looks from Character packs.
        out.append((sprite(f"character-{who}", character["rows"], character["palette"]), False))
    return out


def chunks(values, width, fmt):
    items = [fmt(v) for v in values]
    return [", ".join(items[i:i + width]) for i in range(0, len(items), width)]


# ---------- Swift ----------


def swift_theme(tokens):
    lines = [f"// {HEADER}", "import SwiftUI", "", "/// The korekore design tokens (docs/design/korekore/tokens.json).",
             "public enum KorekoreTheme {", "    public enum Colors {"]
    for name, rgb, usage in colors(tokens):
        lines += [f"        /// {usage}", f"        public static let {camel(name)} = Color(korekoreRGB: 0x{rgb:06X})"]
    lines += ["    }", "", "    /// The bundled fonts (Resources/fonts) by PostScript name.", "    public enum FontName {"]
    for name in [*ROUNDED.values(), *PIXEL.values()]:
        family, weight = name.split("-")
        short = ("rounded" if family == "RoundedMplus1c" else "pixel") + weight
        lines.append(f"        public static let {short} = \"{name}\"")
    lines += ["    }", "", "    public enum Typography {"]
    for name, family, font, size, line_height, weight, spacing, usage in text_styles(tokens):
        lines += [f"        /// {FAMILY_NAMES[family]} {weight}. {usage}",
                  f"        public static let {camel(name)} = KorekoreTextStyle(font: \"{font}\", size: {number(size)}, "
                  f"lineHeight: {number(line_height)}, letterSpacing: {number(spacing)})"]
    lines.append("    }")
    for enum, group in [("Space", "spacing"), ("Radius", "radius"), ("Stroke", "stroke")]:
        lines += ["", f"    public enum {enum} {{"]
        for name, value, usage in metrics(tokens, group):
            short = name.split("-", 1)[1] if "-" in name else name
            short = "s" + short if short[0].isdigit() else short
            lines += [f"        /// {usage}", f"        public static let {camel(short)}: CGFloat = {number(px(value))}"]
        lines.append("    }")
    lines += ["", "    /// Solid ink drop shadows: how far down they fall.", "    public enum Sticker {"]
    for name, value, usage in metrics(tokens, "shadow"):
        lines += [f"        /// {usage}", f"        public static let {camel(name.split('-', 1)[1])}: CGFloat = {number(shadow_offset(value))}"]
    lines += ["    }", "", "    public enum Pixel {"]
    for name, value, usage in metrics(tokens, "pixel"):
        swift_value = number(px(value)) if value.endswith("px") else value
        kind = "CGFloat" if value.endswith("px") else "Int"
        lines += [f"        /// {usage}", f"        public static let {camel(name)}: {kind} = {swift_value}"]
    lines += ["    }", "}", "",
              "/// A type style: the font file, its size, line height and letter spacing, all in points.",
              "public struct KorekoreTextStyle: Sendable {", "    public let font: String", "    public let size: CGFloat",
              "    public let lineHeight: CGFloat", "    public let letterSpacing: CGFloat", "}", "",
              "extension Color {", "    public init(korekoreRGB rgb: UInt32) {",
              "        self.init(.sRGB, red: Double(rgb >> 16 & 0xFF) / 255, green: Double(rgb >> 8 & 0xFF) / 255, "
              "blue: Double(rgb & 0xFF) / 255)",
              "    }", "}", ""]
    return "\n".join(lines)


def swift_sprites(all_sprites):
    lines = [f"// {HEADER}", "", "/// The korekore sprites as palette-indexed pixels (see PixelSprite).",
             "public enum KorekoreSprites {"]
    for s, _ in all_sprites:
        lines += [f"    public static let {camel(s['name'])} = PixelSprite(",
                  f"        width: {s['width']}, height: {s['height']},",
                  f"        palette: [{', '.join(f'0x{c:06X}' for c in s['palette'])}],",
                  "        pixels: ["]
        lines += [f"            {row}," for row in chunks(s["pixels"], s["width"], str)]
        lines += ["        ]", "    )"]
    lines += ["", "    /// Every sprite by its name in docs/design/korekore.", "    public static let all: [String: PixelSprite] = ["]
    lines += [f"        \"{s['name']}\": {camel(s['name'])}," for s, _ in all_sprites]
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


# ---------- Rust ----------


def rust_theme(tokens):
    lines = [f"//! {HEADER}", "//! The korekore design tokens (docs/design/korekore/tokens.json) for iced.", "",
             "use iced::font::{Family, Weight};", "use iced::{Color, Font};", ""]
    for name, rgb, usage in colors(tokens):
        lines += [f"/// {usage}",
                  f"pub const {upper(name)}: Color = Color::from_rgb8(0x{rgb >> 16:02X}, 0x{rgb >> 8 & 0xFF:02X}, 0x{rgb & 0xFF:02X});"]
    lines += ["", "/// A type style: the font, its size, line height and letter spacing, all in logical pixels.",
              "#[derive(Clone, Copy, Debug)]", "pub struct TextStyle {", "    pub font: Font,", "    pub size: f32,",
              "    pub line_height: f32,", "    pub letter_spacing: f32,", "}", ""]
    lines += ["/// The type styles, apart from the colours since some share a name (`box-text`).", "pub mod typography {",
              "    use super::{Family, Font, TextStyle, Weight};"]
    for name, family, _, size, line_height, weight, spacing, usage in text_styles(tokens):
        lines += ["", f"    /// {FAMILY_NAMES[family]} {weight}. {usage}",
                  f"    pub const {upper(name)}: TextStyle = TextStyle {{",
                  "        font: Font {",
                  f"            family: Family::Name(\"{FAMILY_NAMES[family]}\"),",
                  f"            weight: Weight::{RUST_WEIGHTS[weight]},", "            ..Font::DEFAULT", "        },",
                  f"        size: {size:.1f},", f"        line_height: {line_height:.1f},",
                  f"        letter_spacing: {spacing:.1f},", "    };"]
    lines.append("}")
    for group, prefix in [("spacing", ""), ("radius", ""), ("stroke", "")]:
        lines.append("")
        for name, value, usage in metrics(tokens, group):
            lines += [f"/// {usage}", f"pub const {upper(prefix + name)}: f32 = {px(value):.1f};"]
    lines.append("")
    for name, value, usage in metrics(tokens, "shadow"):
        lines += [f"/// How far the solid ink shadow falls. {usage}", f"pub const {upper(name)}: f32 = {shadow_offset(value):.1f};"]
    lines.append("")
    for name, value, usage in metrics(tokens, "pixel"):
        if value.endswith("px"):
            lines += [f"/// {usage}", f"pub const {upper(name)}: f32 = {px(value):.1f};"]
        else:
            lines += [f"/// {usage}", f"pub const {upper(name)}: u32 = {value};"]
    lines.append("")
    return "\n".join(lines)


def rust_sprites(all_sprites, firmware):
    kind = "palette entries in RGB565" if firmware else "palette entries as 0xRRGGBB"
    lines = [f"//! {HEADER}", f"//! The korekore sprites as palette-indexed pixels ({kind}); see `Sprite`.", "",
             "use super::Sprite;", ""]
    chosen = [s for s, on_box in all_sprites if on_box or not firmware]
    for s in chosen:
        palette = [rgb565(c) if firmware else c for c in s["palette"]]
        width = 4 if firmware else 6
        lines += [f"pub static {upper(s['name'])}: Sprite = Sprite {{",
                  f"    width: {s['width']},", f"    height: {s['height']},",
                  f"    palette: &[{', '.join(f'0x{c:0{width}X}' for c in palette)}],", "    pixels: &["]
        lines += [f"        {row}," for row in chunks(s["pixels"], s["width"], str)]
        lines += ["    ],", "};", ""]
    lines += ["/// Every sprite by its name in docs/design/korekore.", "pub static ALL: &[(&str, &Sprite)] = &["]
    lines += [f"    (\"{s['name']}\", &{upper(s['name'])})," for s in chosen]
    lines += ["];", ""]
    return "\n".join(lines)


def firmware_theme(tokens):
    lines = [f"//! {HEADER}", "//! The korekore colours in the screen's RGB565.", ""]
    for name, rgb, usage in colors(tokens):
        lines += [f"/// #{rgb:06X}. {usage}", f"pub const {upper(name)}: u16 = 0x{rgb565(rgb):04X};"]
    lines.append("")
    return "\n".join(lines)


def outputs():
    tokens = load("tokens.json")
    all_sprites = sprites(tokens)
    return {
        "app/Sources/KorekoreUI/KorekoreTheme.swift": swift_theme(tokens),
        "app/Sources/VibeBuddyCore/Korekore/KorekoreSprites.swift": swift_sprites(all_sprites),
        "desktop/src/korekore/theme.rs": rust_theme(tokens),
        "desktop/src/korekore/sprites.rs": rust_sprites(all_sprites, firmware=False),
        "firmware-rs/core/src/korekore/theme.rs": firmware_theme(tokens),
        "firmware-rs/core/src/korekore/sprites.rs": rust_sprites(all_sprites, firmware=True),
    }


def main():
    check = sys.argv[1:] == ["--check"]
    stale = []
    for relative, text in outputs().items():
        path = ROOT / relative
        if path.exists() and path.read_text() == text:
            continue
        stale.append(relative)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if check and stale:
        sys.exit("out of date, run tools/korekore-codegen.py: " + ", ".join(stale))
    for relative in stale:
        print(f"wrote {relative}")


if __name__ == "__main__":
    main()
