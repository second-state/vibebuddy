#!/usr/bin/env python3
"""Rasterize the korekore box screens' type into firmware tables (ADR-0021, docs/design/korekore).

The box screens are set in DotGothic16 at the sizes the design uses, and the "korekore" wordmark in M PLUS Rounded
1c ExtraBold. The firmware has no font engine, so each size is drawn here once, with FreeType through Pillow, as
4-bit coverage (0 = none, 15 = full), and written to firmware-rs/core/src/korekore/glyphs.rs. Only the characters a
size needs are kept: whole printable ASCII for text sizes, a few characters for the large ones.

The fonts are the ones the apps bundle (fonts/korekore, from tools/korekore-fonts.py). Pillow bundles FreeType, so
the output can differ by a pixel between Pillow versions: regenerate and commit, don't compare in CI.

Usage: tools/korekore-box-fonts.py
"""
from pathlib import Path

from PIL import ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "fonts/korekore"
OUT = ROOT / "firmware-rs/core/src/korekore/glyphs.rs"

ASCII = "".join(chr(code) for code in range(0x20, 0x7F)) + "·›‹…×"
# Size in px (the CSS font-size the design uses) and the characters drawn at it.
DOT_SIZES = [
    (9, ASCII),
    (10, ASCII),
    (11, ASCII),
    (12, ASCII),
    (13, ASCII),
    (14, ASCII),
    (16, ASCII),
    (18, ASCII),
    (22, ASCII),
    (30, " 0123456789:ABCEFKORSU"),
    (34, "これ!"),
    (36, "YAT!"),
    (38, "0123456789:"),
]
WORDMARK = "korekore"
WORDMARK_SIZES = [12, 14, 40]


def coverage(mask, width, height):
    """4-bit coverage, two pixels a byte, low nibble first, row by row."""
    values = [round(mask.getpixel((x, y)) * 15 / 255) for y in range(height) for x in range(width)]
    if len(values) % 2:
        values.append(0)
    return bytes(values[i] | values[i + 1] << 4 for i in range(0, len(values), 2))


def glyph(font, character):
    mask, (left, top) = font.getmask2(character, mode="L")
    width, height = mask.size
    return {
        "char": character,
        "advance": round(font.getlength(character)),
        "left": left,
        "top": top,
        "width": width,
        "height": height,
        "alpha": coverage(mask, width, height) if width and height else b"",
    }


def rust_bytes(data, indent="    "):
    lines = []
    for start in range(0, len(data), 24):
        lines.append(indent + " ".join(f"0x{byte:02X}," for byte in data[start : start + 24]))
    return "\n".join(lines)


def face(name, size, characters):
    font = ImageFont.truetype(str(FONTS / "DotGothic16-Regular.ttf"), size)
    ascent, descent = font.getmetrics()
    glyphs = sorted((glyph(font, character) for character in dict.fromkeys(characters)), key=lambda g: ord(g["char"]))
    alpha = b""
    rows = []
    for g in glyphs:
        rows.append(
            f"    Glyph {{ code: {ord(g['char'])}, advance: {g['advance']}, left: {g['left']}, top: {g['top']}, "
            f"width: {g['width']}, height: {g['height']}, at: {len(alpha)} }},"
        )
        alpha += g["alpha"]
    return (
        f"/// DotGothic16 at {size} px.\n"
        f"pub static {name}: Face = Face {{\n    size: {size},\n    ascent: {ascent},\n    descent: {descent},\n"
        f"    glyphs: &[\n{chr(10).join('    ' + row for row in rows)}\n    ],\n    alpha: &[\n{rust_bytes(alpha, '        ')}\n    ],\n}};\n"
    )


def wordmark(size):
    font = ImageFont.truetype(str(FONTS / "MPLUSRounded1c-ExtraBold.ttf"), size)
    mask, _ = font.getmask2(WORDMARK, mode="L")
    width, height = mask.size
    return (
        f"/// \"{WORDMARK}\" in M PLUS Rounded 1c ExtraBold at {size} px, cropped to its ink.\n"
        f"pub static WORDMARK_{size}: Bitmap = Bitmap {{\n    width: {width},\n    height: {height},\n"
        f"    alpha: &[\n{rust_bytes(coverage(mask, width, height), '        ')}\n    ],\n}};\n"
    )


def main():
    parts = [
        "//! Generated by tools/korekore-box-fonts.py from fonts/korekore. Do not edit.\n"
        "//! The korekore box screens' type as 4-bit coverage, two pixels a byte, low nibble first.\n\n"
        "use super::text::{Bitmap, Face, Glyph};\n"
    ]
    for size, characters in DOT_SIZES:
        parts.append(face(f"DOT_{size}", size, characters))
    for size in WORDMARK_SIZES:
        parts.append(wordmark(size))
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
