#!/usr/bin/env python3
"""Build the XGGF status font table, firmware-xggf/main/font.{h,c}.

The 64x8 panel draws its status labels with a 5x7 ASCII font. The glyphs come from the
petabyt "7x5" font vendored at fonts/petabyt-5x7/font.h (MIT License, Copyright (c) 2020
Petabyte; the license is kept next to it as MIT-petabyt-font.txt). This script converts
its 7-row x 5-column "#"/space pictures into the packed rows the firmware renders.

The table covers every printable ASCII character (0x20-0x7E), ascending and contiguous,
so a lookup is one range check and a subtraction. Upstream quirks the conversion pins
down:
  - the trailing {0, ...} fallback glyph and the control-keyed {1, ...} glyph are
    skipped (petabyt's fallback shape is reused for any printable character upstream
    left undefined, and the header lists those characters);
  - '-' is defined twice with different shapes; the first definition (the row-3
    three-pixel dash) wins, and any other differing duplicate fails the build ('_' is
    duplicated too, but both copies are identical);
  - petabyt hugs the left edge of the 5-column cell for narrow shapes ('I', '!', '1',
    ':' ...), so each glyph's ink is shifted to center it horizontally in its cell,
    the one modification this build makes to the upstream shapes.

Usage: tools/make-xggf-font.py [--check]
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "fonts/petabyt-5x7/font.h"
HEADER = ROOT / "firmware-xggf/main/font.h"
TABLE = ROOT / "firmware-xggf/main/font.c"

WIDTH = 5
HEIGHT = 7
FIRST = 0x20
LAST = 0x7E

ENTRY_RE = re.compile(r"\{('(?:\\.|[^\\'])'|[^,{}]+),\s*\{([^{}]*)\}\}", re.S)
ROW_RE = re.compile(r'"([^"\n]*)"')


def center(rows):
    """Shift a glyph's ink so it sits horizontally centered in its cell."""
    inked = [col for col in range(WIDTH) if any(row[col] == "#" for row in rows)]
    if not inked:
        return rows
    shift = (WIDTH - 1 - inked[0] - inked[-1]) // 2
    if shift == 0:
        return rows
    moved = [""] * HEIGHT
    for y, row in enumerate(rows):
        moved[y] = ([" "] * WIDTH)
        for col in range(WIDTH):
            target = col + shift
            if 0 <= target < WIDTH:
                moved[y][target] = row[col]
        moved[y] = "".join(moved[y])
    return moved


def pack(rows):
    return [sum(1 << (WIDTH - 1 - col) for col in range(WIDTH) if row[col] == "#")
            for row in rows]


def parse_glyphs(text):
    """Return {printable ASCII char: [7 ints]}, first definition winning."""
    glyphs = {}
    for key_field, body in ENTRY_RE.findall(text):
        if not key_field.startswith("'"):
            continue  # the {0, ...} terminator and the {1, ...} extended glyph
        key = re.sub(r"\\(.)", r"\1", key_field[1:-1])
        if len(key) != 1 or not FIRST <= ord(key) <= LAST:
            continue
        rows = ROW_RE.findall(body)
        if len(rows) != HEIGHT or any(len(row) != WIDTH or set(row) - set(" #") for row in rows):
            sys.exit(f"make-xggf-font: unparseable glyph for {key!r}")
        if key in glyphs:
            rows_packed = pack(center(rows))
            if glyphs[key] != rows_packed and key != "-":
                sys.exit(f"make-xggf-font: duplicate glyph for {key!r}")
            continue
        glyphs[key] = pack(center(rows))
    return glyphs


def fallback_glyph():
    """Petabyt's own fallback: the solid 5x7 block it keys as {0, ...}."""
    return [(1 << WIDTH) - 1] * HEIGHT


def load_glyphs():
    expanded = subprocess.run(["cc", "-E", "-P", str(SOURCE)], capture_output=True,
                              text=True, check=True).stdout
    glyphs = parse_glyphs(expanded)
    missing = [chr(c) for c in range(FIRST, LAST + 1) if chr(c) not in glyphs]
    for key in missing:
        glyphs[key] = fallback_glyph()
    return glyphs, missing


def c_char(key):
    return {"'": "\\'", "\\": "\\\\"}.get(key, key)


def generate(glyphs, missing):
    note = (f"Generated by tools/make-xggf-font.py from {SOURCE.relative_to(ROOT)}, the petabyt\n"
            f'"7x5" font (MIT License, Copyright (c) 2020 Petabyte; license at\n'
            f"fonts/petabyt-5x7/MIT-petabyt-font.txt). Do not edit by hand.")
    fallback_note = ("" if not missing else
                     f"\nUpstream leaves {' '.join(repr(c) for c in missing)} undefined; those cells carry\n"
                     "petabyt's solid fallback block.")
    header = f"""#ifndef XGGF_FONT_H
#define XGGF_FONT_H

#include <stdint.h>

/* {note} */

enum {{ XGGF_FONT_WIDTH = {WIDTH}, XGGF_FONT_HEIGHT = {HEIGHT},
       XGGF_FONT_COUNT = {LAST - FIRST + 1} }};

/* Seven rows per glyph, five columns per row packed in the low five bits with bit 4
   the leftmost column: row y lights column col when rows[y] & (0x10u >> col).{fallback_note} */
typedef struct {{
    char c;
    uint8_t rows[XGGF_FONT_HEIGHT];
}} xggf_glyph;

/* The {LAST - FIRST + 1} printable ASCII characters 0x{FIRST:02X}-0x{LAST:02X} in ascending order. */
extern const xggf_glyph xggf_font[XGGF_FONT_COUNT];

const xggf_glyph *xggf_font_glyph(char c);

#endif
"""
    def entry(c):
        rows = ", ".join(f"0x{v:02X}" for v in glyphs[chr(c)])
        return f"    {{'{c_char(chr(c))}', {{{rows}}}}},"

    body = "\n".join(entry(c) for c in range(FIRST, LAST + 1))
    table = f"""/* {note} */
#include "font.h"

#include <stddef.h>

const xggf_glyph xggf_font[XGGF_FONT_COUNT] = {{
{body}
}};

const xggf_glyph *xggf_font_glyph(char c)
{{
    unsigned key = (unsigned char)c;
    if (key < 0x{FIRST:02X} || key > 0x{LAST:02X}) return NULL;
    const xggf_glyph *g = &xggf_font[key - 0x{FIRST:02X}];
    return g->c == c ? g : NULL;
}}
"""
    return {HEADER: header, TABLE: table}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="verify the committed files match the vendored font; exit 1 if not")
    args = parser.parse_args()

    for path, content in generate(*load_glyphs()).items():
        current = path.read_text() if path.exists() else None
        if content == current:
            continue
        if args.check:
            sys.exit(f"make-xggf-font: {path.relative_to(ROOT)} is out of date; "
                     "run tools/make-xggf-font.py and commit what it writes")
        path.write_text(content)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
